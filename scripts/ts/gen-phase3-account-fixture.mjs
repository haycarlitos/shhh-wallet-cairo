#!/usr/bin/env node
/**
 * Phase 3 end-to-end account fixture generator.
 *
 * Given a deterministic test OutsideExecution + expected account
 * address + chain_id, emits the ready-to-submit owner envelope:
 *
 *     [ SIG_VERSION_V2_SNIP12, owner_id=0, kind_tag='ED25519',
 *       <EdDSASignatureWithHint calldata from garaga> ]
 *
 * The test deploys ShhhAccount at the fixed address, cheats chain_id
 * to match, and submits `execute_from_outside_v2(OE, envelope)`.
 */

import * as ed from '@noble/ed25519';
import * as garaga from 'garaga';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { SIG_VERSION_V2_SNIP12, computeSnip12Hash } from './snip12-hash.ts';

await garaga.init();

// ----------------------------------------------------------------
// Fixed fixture inputs (match tests/account_phase3.cairo)
// ----------------------------------------------------------------

const PRIV = new Uint8Array(32);
for (let i = 0; i < 32; i++) PRIV[i] = i + 1;

// Account address chosen to be deployed via snforge `deploy_at`.
const ACCOUNT_ADDR = 0xACC0n;
// Target contract address — the account will call this in the OE multicall.
const TARGET_ADDR = 0xBEEFn;
// Chain id — tests use 'SN_MAIN' short-string for parity with SNIP-12 tests.
const CHAIN_ID_SHORT_STRING = 'SN_MAIN';
const CHAIN_ID_FELT = BigInt('0x' + Buffer.from(CHAIN_ID_SHORT_STRING).toString('hex'));

const SELECTOR_SET_VALUE = '0x' + 'set_value'.split('').map((c) => c.charCodeAt(0).toString(16)).join('');
// We compute the selector the way Starknet does it: starknetKeccak(name).
// Use starknet.js to avoid drift.
import { hash as snHash } from 'starknet';
const SELECTOR = BigInt(snHash.getSelectorFromName('set_value'));

const OE = {
  caller: BigInt('0x' + Buffer.from('ANY_CALLER').toString('hex')),
  nonce: 0x2030405060708n,
  execute_after: 100n,
  execute_before: 3000n,
  calls: [
    {
      contractAddress: '0x' + TARGET_ADDR.toString(16),
      entrypoint: 'set_value',
      calldata: ['0xCAFE'],
    },
  ],
};

// ----------------------------------------------------------------
// Pipeline
// ----------------------------------------------------------------

function bytesToLeBigInt(bytes) {
  let x = 0n;
  for (let i = bytes.length - 1; i >= 0; i--) x = (x << 8n) | BigInt(bytes[i]);
  return x;
}
function bytesToLeU256(bytes) {
  let low = 0n;
  let high = 0n;
  for (let i = 0; i < 16; i++) low += BigInt(bytes[i]) << BigInt(8 * i);
  for (let i = 0; i < 16; i++) high += BigInt(bytes[16 + i]) << BigInt(8 * i);
  return { low, high };
}
function hashToHexAsciiBytes(h) {
  const hex = h.toString(16).padStart(64, '0');
  return new TextEncoder().encode(hex);
}

const pub = await ed.getPublicKeyAsync(PRIV);
const pubPy = bytesToLeU256(pub);

const messageHash = computeSnip12Hash(OE, ACCOUNT_ADDR, CHAIN_ID_FELT);
const signedBytes = hashToHexAsciiBytes(messageHash);
const sig = await ed.signAsync(signedBytes, PRIV);
const R = sig.slice(0, 32);
const s = sig.slice(32, 64);

const verifierCalldata = garaga.eddsaCalldataBuilder(
  bytesToLeBigInt(R),
  bytesToLeBigInt(s),
  bytesToLeBigInt(pub),
  signedBytes,
  false,
);

// Prepend the owner-envelope header: [version, owner_id, kind_tag]
const KIND_ED25519 = BigInt('0x' + Buffer.from('ED25519').toString('hex'));
const fullEnvelope = [
  BigInt(SIG_VERSION_V2_SNIP12),
  0n,                    // owner_id = 0 (primary)
  KIND_ED25519,
  ...verifierCalldata,
];

// ----------------------------------------------------------------
// Emit Cairo fixture
// ----------------------------------------------------------------

const felt = (x) => '0x' + x.toString(16);

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-phase3-account-fixture.mjs.
//! Do not edit by hand.

pub fn phase3_account_addr() -> felt252 {
    ${felt(ACCOUNT_ADDR)}
}

pub fn phase3_target_addr() -> felt252 {
    ${felt(TARGET_ADDR)}
}

pub fn phase3_chain_id() -> felt252 {
    '${CHAIN_ID_SHORT_STRING}'
}

pub fn phase3_nonce() -> felt252 {
    ${felt(OE.nonce)}
}

pub fn phase3_execute_after() -> u64 {
    ${OE.execute_after.toString()}
}

pub fn phase3_execute_before() -> u64 {
    ${OE.execute_before.toString()}
}

pub fn phase3_pubkey_low() -> felt252 {
    ${felt(pubPy.low)}
}

pub fn phase3_pubkey_high() -> felt252 {
    ${felt(pubPy.high)}
}

pub fn phase3_message_hash() -> felt252 {
    ${felt(messageHash)}
}

pub fn phase3_set_value_selector() -> felt252 {
    ${felt(SELECTOR)}
}

pub fn phase3_set_value_arg() -> felt252 {
    0xCAFE
}

pub fn phase3_signature_envelope() -> Array<felt252> {
    array![
${fullEnvelope.map((e) => `        ${felt(e)},`).join('\n')}
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/account_phase3_fixture.cairo');
writeFileSync(out, cairo);
console.log('Wrote', out);
console.log('account_addr   =', felt(ACCOUNT_ADDR));
console.log('chain_id       =', CHAIN_ID_SHORT_STRING, '=', felt(CHAIN_ID_FELT));
console.log('message_hash   =', felt(messageHash));
console.log('envelope felts =', fullEnvelope.length);
console.log('pubkey.low     =', felt(pubPy.low));
console.log('pubkey.high    =', felt(pubPy.high));
