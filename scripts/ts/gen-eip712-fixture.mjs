#!/usr/bin/env node
/**
 * EIP-712 fixture for V8 EIP712Secp256k1Verifier.
 *
 * Uses ethers `Wallet.signTypedData(domain, types, value)` — the exact
 * recipe MetaMask follows for `eth_signTypedData_v4`.
 *
 * Domain shape:
 *   EIP712Domain(string name,string version,uint256 chainId,bytes32 salt)
 *
 * `salt` carries the V8 account address (lossless 32-byte). We can't
 * use `verifyingContract` because ethers v6 tries to ENS-resolve any
 * non-address value placed there. `salt` is also a standard EIP-712
 * domain field, MetaMask renders it as bytes32, and signatures
 * remain bound per-account.
 *
 * Struct shape:
 *   MessageHash(bytes32 hash)
 *
 * Test inputs (must match the Cairo test exactly so the on-chain
 * recompute lands on the same final hash):
 *   - chainId  = 0     (snforge default; Cairo test cheats this)
 *   - salt     = 0x1d6e (the address Cairo test deploys the verifier
 *                to via deploy_at; the verifier reads
 *                `get_contract_address()` and feeds it into the salt
 *                slot of the domain separator)
 *   - hash     = MESSAGE_HASH (the Phase-1 SNIP-12 vector)
 */

import { Wallet, getBytes, hexlify, TypedDataEncoder } from 'ethers';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PRIV_HEX = '0x0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20';
const wallet = new Wallet(PRIV_HEX);

const MESSAGE_HASH = 0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2fn;

const ACCOUNT_ADDR_BIG = 0x1d6en;
const ACCOUNT_ADDR_HEX = '0x' + ACCOUNT_ADDR_BIG.toString(16).padStart(64, '0');

const CHAIN_ID = 0n; // snforge default

const domain = {
  name: 'Shhh',
  version: '1',
  chainId: CHAIN_ID,
  salt: ACCOUNT_ADDR_HEX,
};

const types = {
  // ethers strips EIP712Domain from `types` automatically.
  MessageHash: [{ name: 'hash', type: 'bytes32' }],
};

const value = {
  hash: '0x' + MESSAGE_HASH.toString(16).padStart(64, '0'),
};

// ethers v6 derives the EIP712Domain typehash from which fields the
// `domain` object has. With { name, version, chainId, salt } it
// produces the canonical
//   EIP712Domain(string name,string version,uint256 chainId,bytes32 salt)
// which matches our Cairo DOMAIN_TYPEHASH constant.
const sigHex = await wallet.signTypedData(domain, types, value);

// Sanity: ethers's TypedDataEncoder lets us recompute the final hash
// off-chain so the Cairo test can compare on the wire if needed.
const encodedHash = TypedDataEncoder.hash(domain, types, value);

const sigBytes = getBytes(sigHex);
if (sigBytes.length !== 65) throw new Error('expected 65-byte sig');
const rBytes = sigBytes.slice(0, 32);
const sBytes = sigBytes.slice(32, 64);
const vByte = sigBytes[64];
const yParity = vByte === 28 ? 1n : 0n;

const pubBytes = getBytes(wallet.signingKey.publicKey);
if (pubBytes[0] !== 0x04 || pubBytes.length !== 65) throw new Error('bad pubkey');
const xBytes = pubBytes.slice(1, 33);
const yBytes = pubBytes.slice(33, 65);

function bytesBeToU256(b) {
  let x = 0n;
  for (let i = 0; i < b.length; i++) x = (x << 8n) | BigInt(b[i]);
  return { low: x & ((1n << 128n) - 1n), high: x >> 128n };
}

const pub = { x: bytesBeToU256(xBytes), y: bytesBeToU256(yBytes) };
const r = bytesBeToU256(rBytes);
const s = bytesBeToU256(sBytes);
const felt = (x) => '0x' + x.toString(16);

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-eip712-fixture.mjs.
//! Do not edit by hand. Re-run if domain shape, struct shape, or
//! fixture inputs change.
//!
//! Recipe matches ethers \`Wallet.signTypedData(domain, types, value)\`,
//! which is exactly what MetaMask \`eth_signTypedData_v4\` returns.
//!
//! Test conditions the Cairo test MUST cheat to:
//!   chain_id      = 0
//!   account_addr  = ${felt(ACCOUNT_ADDR_BIG)} (deploy_at this address)
//!
//! Domain   : Shhh v1 on chain 0 with salt = ${felt(ACCOUNT_ADDR_BIG)}
//! Struct   : MessageHash{hash: ${felt(MESSAGE_HASH)}}
//! Final h  : ${encodedHash}
//! Pubkey X : ${hexlify(xBytes).slice(2)}
//! Pubkey Y : ${hexlify(yBytes).slice(2)}
//! r        : ${hexlify(rBytes).slice(2)}
//! s        : ${hexlify(sBytes).slice(2)}
//! v        : ${vByte}  (y_parity = ${yParity})

pub fn eip712_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn eip712_account_address() -> felt252 {
    ${felt(ACCOUNT_ADDR_BIG)}
}

pub fn eip712_chain_id() -> felt252 {
    0
}

pub fn eip712_pubkey() -> Array<felt252> {
    array![
        ${felt(pub.x.low)},
        ${felt(pub.x.high)},
        ${felt(pub.y.low)},
        ${felt(pub.y.high)},
    ]
}

pub fn eip712_signature() -> Array<felt252> {
    array![
        ${felt(r.low)},
        ${felt(r.high)},
        ${felt(s.low)},
        ${felt(s.high)},
        ${felt(yParity)},
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/signer_eip712_fixture.cairo');
writeFileSync(out, cairo);

console.log('Wrote', out);
console.log('domain.salt        =', ACCOUNT_ADDR_HEX);
console.log('domain.chainId     =', CHAIN_ID);
console.log('encoded final hash =', encodedHash);
console.log('r                  =', hexlify(rBytes));
console.log('s                  =', hexlify(sBytes));
console.log('v                  =', vByte, '→ y_parity', yParity);
