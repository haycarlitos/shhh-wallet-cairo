#!/usr/bin/env node
/**
 * STARK SNIP-12 fixture for V8 StarkSnip12Verifier.
 *
 * Uses starknet.js `typedData.getMessageHash(td, signerAccount)` + STARK
 * ECDSA — the exact recipe Starknet browser wallets (Bramble, Braavos,
 * Ready/Argent, OpenZeppelin accounts) follow for `wallet_signTypedData`.
 * The wallet always folds ITS OWN account address into the hash, which is
 * why a raw-hash `StarkVerifier` can never check these signatures.
 *
 * Typed data (SNIP-12 revision 1):
 *   StarknetDomain { name: 'Shhh', version: '1', chainId: <chain>, revision: '1' }
 *   Approval { Wallet: ContractAddress, Hash: felt }
 *
 *   - `Wallet` is the ShhhAccount the approval is for (the verifier reads
 *     `get_contract_address()`), so a signature is bound to one wallet.
 *   - `Hash` is the SNIP-12 OE hash the account passed to verify().
 *
 * Test inputs (must match the Cairo test exactly):
 *   - chainId        = 'SN_MAIN' (the Cairo test cheats chain_id to this)
 *   - wallet address = 0x5eba (the Cairo test deploys the verifier here)
 *   - signer account = 0x0123abc (the external wallet's address; part of the pubkey)
 *   - hash           = MESSAGE_HASH (the Phase-1 SNIP-12 vector)
 */

import { TypedDataRevision, ec, num, shortString, typedData } from 'starknet';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PRIV = '0x3c1e9550e66958296d11b60f8e8e7a7ad990d07fa65d5f7652c4a6c87d4e3cc';
const PUB = ec.starkCurve.getStarkKey(PRIV);

const MESSAGE_HASH = 0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2n;
const WALLET_ADDR = 0x5eban;
const SIGNER_ADDR = 0x123abcn;
const CHAIN_ID = 'SN_MAIN';

const felt = (x) => num.toHex(x);

export function approvalTypedData(walletAddress, messageHash, chainId) {
  return {
    types: {
      StarknetDomain: [
        { name: 'name', type: 'shortstring' },
        { name: 'version', type: 'shortstring' },
        { name: 'chainId', type: 'shortstring' },
        { name: 'revision', type: 'shortstring' },
      ],
      Approval: [
        { name: 'Wallet', type: 'ContractAddress' },
        { name: 'Hash', type: 'felt' },
      ],
    },
    primaryType: 'Approval',
    domain: { name: 'Shhh', version: '1', chainId, revision: '1' },
    message: { Wallet: felt(walletAddress), Hash: felt(messageHash) },
  };
}

const td = approvalTypedData(WALLET_ADDR, MESSAGE_HASH, CHAIN_ID);
const finalHash = typedData.getMessageHash(td, felt(SIGNER_ADDR));
const sig = ec.starkCurve.sign(finalHash, PRIV);
if (!ec.starkCurve.verify(sig, finalHash, ec.starkCurve.getPublicKey(PRIV))) throw new Error('self-check failed');

const rev1 = TypedDataRevision.ACTIVE;
const domainTypeHash = typedData.getTypeHash(td.types, 'StarknetDomain', rev1);
const approvalTypeHash = typedData.getTypeHash(td.types, 'Approval', rev1);
const domainHash = typedData.getStructHash(td.types, 'StarknetDomain', td.domain, rev1);
const structHash = typedData.getStructHash(td.types, 'Approval', td.message, rev1);

// Recompute by hand with the exact recipe the Cairo verifier uses, so a
// drift between the two is caught here before it reaches the test.
// `poseidonHashMany` is Cairo's `poseidon_hash_span`.
const poseidon = (xs) => ec.starkCurve.poseidonHashMany(xs.map((x) => BigInt(x)));
const domainByHand = poseidon([
  domainTypeHash,
  shortString.encodeShortString('Shhh'),
  1n,
  shortString.encodeShortString(CHAIN_ID),
  1n,
]);
const structByHand = poseidon([approvalTypeHash, WALLET_ADDR, MESSAGE_HASH]);
const finalByHand = poseidon([
  shortString.encodeShortString('StarkNet Message'),
  domainByHand,
  SIGNER_ADDR,
  structByHand,
]);
if (BigInt(domainByHand) !== BigInt(domainHash)) throw new Error('domain hash recipe drift');
if (BigInt(structByHand) !== BigInt(structHash)) throw new Error('struct hash recipe drift');
if (BigInt(finalByHand) !== BigInt(finalHash)) throw new Error('final hash recipe drift');

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-stark-snip12-fixture.mjs.
//! Do not edit by hand. Re-run if the domain, the struct, or the
//! fixture inputs change.
//!
//! Recipe matches starknet.js \`typedData.getMessageHash(td, signer)\` +
//! STARK ECDSA, which is what \`wallet_signTypedData\` returns in Bramble,
//! Braavos, Ready/Argent and OpenZeppelin accounts.
//!
//! Test conditions the Cairo test MUST cheat to:
//!   chain_id       = '${CHAIN_ID}'
//!   wallet address = ${felt(WALLET_ADDR)} (deploy_at this address)
//!
//! Domain        : Shhh v1 rev 1 on ${CHAIN_ID}
//! Struct        : Approval{Wallet, Hash}
//!   Wallet      : ${felt(WALLET_ADDR)}
//!   Hash        : ${felt(MESSAGE_HASH)}
//! Signer        : ${felt(SIGNER_ADDR)}
//! Domain type   : ${domainTypeHash}
//! Approval type : ${approvalTypeHash}
//! Final hash    : ${finalHash}

pub fn stark_snip12_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn stark_snip12_wallet_address() -> felt252 {
    ${felt(WALLET_ADDR)}
}

pub fn stark_snip12_chain_id() -> felt252 {
    '${CHAIN_ID}'
}

pub fn stark_snip12_final_hash() -> felt252 {
    ${finalHash}
}

pub fn stark_snip12_pubkey() -> Array<felt252> {
    array![${PUB}, ${felt(SIGNER_ADDR)}]
}

pub fn stark_snip12_signature() -> Array<felt252> {
    array![
        ${felt(sig.r)},
        ${felt(sig.s)},
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/signer_stark_snip12_fixture.cairo');
writeFileSync(out, cairo);

console.log('Wrote', out);
console.log('APPROVAL_TYPE_HASH =', approvalTypeHash);
console.log('DOMAIN_TYPE_HASH   =', domainTypeHash);
console.log('final hash         =', finalHash);
