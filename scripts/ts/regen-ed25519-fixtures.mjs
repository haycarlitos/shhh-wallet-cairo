#!/usr/bin/env node
/**
 * Ed25519 fixture generator for V8 verifier tests.
 *
 * Produces a Cairo-ready (message_hash, pubkey, signature_envelope[])
 * tuple that the Ed25519Verifier in src/signer/ed25519/verifier.cairo
 * accepts end-to-end.
 *
 * Run: `node scripts/ts/regen-ed25519-fixtures.mjs`
 *
 * Dependencies: @noble/ed25519 ≥ 3.1.0, garaga ≥ 1.0.1 (Cairo-side
 * pinned to the same tag in Scarb.toml so hints agree).
 */

import * as ed from '@noble/ed25519';
import * as garaga from 'garaga';

// Initialize Garaga's WASM bundle before calling any builder.
await garaga.init();

// ----------------------------------------------------------------
// Deterministic fixture inputs
// ----------------------------------------------------------------

// Private key: 0x01, 0x02, ..., 0x20 (32 bytes). Deterministic.
const PRIV = new Uint8Array(32);
for (let i = 0; i < 32; i++) PRIV[i] = i + 1;

// Message hash used by the Cairo positive test. Must fit in felt252 (252
// bits). We use the SNIP-12 hash output of the minimal-OE fixture from
// tests/snip12_hash.cairo — an organic link between Phases 1 and 2 and
// a value known to be a valid felt252.
const MESSAGE_HASH = BigInt(
  '0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2f',
);

// ----------------------------------------------------------------
// Helpers
// ----------------------------------------------------------------

function bytesToLeU256(bytes) {
  // bytes[0] is LSB. Return (low_u128, high_u128) as bigints.
  let low = 0n;
  let high = 0n;
  for (let i = 0; i < 16; i++) low += BigInt(bytes[i]) << BigInt(8 * i);
  for (let i = 0; i < 16; i++) high += BigInt(bytes[16 + i]) << BigInt(8 * i);
  return { low, high };
}

function bytesToLeBigInt(bytes) {
  let x = 0n;
  for (let i = bytes.length - 1; i >= 0; i--) x = (x << 8n) | BigInt(bytes[i]);
  return x;
}

function hashToHexAsciiBytes(h) {
  const hex = h.toString(16).padStart(64, '0'); // 32 bytes -> 64 ASCII chars
  return new TextEncoder().encode(hex);
}

// ----------------------------------------------------------------
// Build the fixture
// ----------------------------------------------------------------

const pub = await ed.getPublicKeyAsync(PRIV);
const msg = hashToHexAsciiBytes(MESSAGE_HASH);
const sig = await ed.signAsync(msg, PRIV);
const R = sig.slice(0, 32);
const s = sig.slice(32, 64);

const pubPy = bytesToLeU256(pub);
const sigRy = bytesToLeU256(R);
const sigS = bytesToLeU256(s);

// Garaga's npm builder consumes (ry, s, py, msg, prependPublickey=false)
// and returns a bigint[] calldata array containing hints.
//
// Return shape (verified empirically against V7 fixtures):
//   [ Ry_low, Ry_high, s_low, s_high,
//     msg_len, msg_byte_0, ..., msg_byte_{msg_len-1},
//     ...msm_hint...,
//     ...sqrt_Rx_hint...,
//     ...sqrt_Px_hint... ]
const calldata = garaga.eddsaCalldataBuilder(
  bytesToLeBigInt(R),   // Ry_twisted_le as bigint
  bytesToLeBigInt(s),   // s as bigint
  bytesToLeBigInt(pub), // Py_twisted_le as bigint
  msg,                  // signed bytes (Uint8Array)
  false,
);

// ----------------------------------------------------------------
// Emit Cairo fixture
// ----------------------------------------------------------------

function felt(x) {
  return '0x' + x.toString(16);
}

const envelope = calldata.map(felt);

const cairo = `//! AUTO-GENERATED by scripts/ts/regen-ed25519-fixtures.mjs
//! Do not edit by hand. Re-run the generator if the Ed25519 verifier
//! class or Garaga hint layout changes.
//!
//! Private key: ${Array.from(PRIV).map(b => b.toString(16).padStart(2, '0')).join('')}
//! Pubkey    : ${Array.from(pub).map(b => b.toString(16).padStart(2, '0')).join('')}
//! Message   : ${Array.from(msg).map(b => String.fromCharCode(b)).join('')}
//! Signature : R=${Array.from(R).map(b => b.toString(16).padStart(2, '0')).join('')}
//!             s=${Array.from(s).map(b => b.toString(16).padStart(2, '0')).join('')}

pub fn fixture_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn fixture_pubkey_low() -> felt252 {
    ${felt(pubPy.low)}
}

pub fn fixture_pubkey_high() -> felt252 {
    ${felt(pubPy.high)}
}

pub fn fixture_signature_envelope() -> Array<felt252> {
    array![
${envelope.map(e => `        ${e},`).join('\n')}
    ]
}
`;

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const cairoOut = resolve(here, '../../tests/signer_ed25519_fixture.cairo');
writeFileSync(cairoOut, cairo);

console.log('Wrote', cairoOut);
console.log('Envelope length:', envelope.length, 'felts');
console.log('pubkey.low  =', felt(pubPy.low));
console.log('pubkey.high =', felt(pubPy.high));
console.log('message_hash =', felt(MESSAGE_HASH));
