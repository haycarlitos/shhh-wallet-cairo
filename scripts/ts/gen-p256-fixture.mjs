#!/usr/bin/env node
/**
 * P-256 fixture generator for V8 WebAuthnP256Verifier tests.
 *
 * @noble/curves' `p256.sign` in v2 returns a 64-byte compact
 * signature without a recovery bit. Rather than reach for the internal
 * Signature API to compute parity, we emit BOTH candidates and the
 * Cairo happy-path test picks the one that recovers the stored pubkey.
 * Either one MUST verify; if neither does, the verifier is broken.
 *
 * Same Phase 1 SNIP-12 message hash as the Ed25519 / secp256k1
 * fixtures so all three signer kinds share one canonical signed value.
 */

import { p256 } from '@noble/curves/nist.js';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PRIV = new Uint8Array(32);
for (let i = 0; i < 32; i++) PRIV[i] = i + 1;

const MESSAGE_HASH = 0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2fn;

const hashBytes = new Uint8Array(32);
{
  let h = MESSAGE_HASH;
  for (let i = 31; i >= 0; i--) {
    hashBytes[i] = Number(h & 0xffn);
    h >>= 8n;
  }
}

// noble-curves v2 defaults to `prehash: true` — it SHA-256s the input
// before signing. We want the verifier to check a signature over the
// raw 32-byte hash, so disable prehashing.
const sigBytes = p256.sign(hashBytes, PRIV, { prehash: false });
if (sigBytes.length !== 64) throw new Error('Unexpected sig length');
const rBytes = sigBytes.slice(0, 32);
const sBytes = sigBytes.slice(32, 64);

const pubBytes = p256.getPublicKey(PRIV, false);
if (pubBytes[0] !== 0x04 || pubBytes.length !== 65) {
  throw new Error('Unexpected pubkey encoding');
}
const xBytes = pubBytes.slice(1, 33);
const yBytes = pubBytes.slice(33, 65);

function bytesBeToU256(b) {
  let x = 0n;
  for (let i = 0; i < b.length; i++) x = (x << 8n) | BigInt(b[i]);
  const low = x & ((1n << 128n) - 1n);
  const high = x >> 128n;
  return { low, high };
}

const pub = { x: bytesBeToU256(xBytes), y: bytesBeToU256(yBytes) };
const r = bytesBeToU256(rBytes);
const s = bytesBeToU256(sBytes);

const felt = (x) => '0x' + x.toString(16);

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-p256-fixture.mjs.
//! Do not edit by hand.
//!
//! Private key: ${Buffer.from(PRIV).toString('hex')}
//! Signed hash: ${felt(MESSAGE_HASH)}
//! Pubkey X   : ${Buffer.from(xBytes).toString('hex')}
//! Pubkey Y   : ${Buffer.from(yBytes).toString('hex')}
//! r          : ${Buffer.from(rBytes).toString('hex')}
//! s          : ${Buffer.from(sBytes).toString('hex')}
//!
//! noble-curves v2 does NOT return a recovery bit — the happy-path
//! test tries both y_parity candidates (0 and 1) and expects one to
//! verify. The wrong one is a useful negative fixture: it cannot
//! recover the correct pubkey, so the verifier returns false.

pub fn p256_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn p256_pubkey() -> Array<felt252> {
    array![
        ${felt(pub.x.low)},
        ${felt(pub.x.high)},
        ${felt(pub.y.low)},
        ${felt(pub.y.high)},
    ]
}

pub fn p256_signature_y_parity_0() -> Array<felt252> {
    array![
        ${felt(r.low)},
        ${felt(r.high)},
        ${felt(s.low)},
        ${felt(s.high)},
        0,
    ]
}

pub fn p256_signature_y_parity_1() -> Array<felt252> {
    array![
        ${felt(r.low)},
        ${felt(r.high)},
        ${felt(s.low)},
        ${felt(s.high)},
        1,
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/signer_p256_fixture.cairo');
writeFileSync(out, cairo);

console.log('Wrote', out);
console.log('message_hash =', felt(MESSAGE_HASH));
console.log('pubkey.x     =', felt(pub.x.low), felt(pub.x.high));
console.log('pubkey.y     =', felt(pub.y.low), felt(pub.y.high));
console.log('r            =', felt(r.low), felt(r.high));
console.log('s            =', felt(s.low), felt(s.high));
