#!/usr/bin/env node
/**
 * secp256k1 fixture generator for V8 Secp256k1Verifier tests.
 *
 * Signs the Phase 1 SNIP-12 OE hash using a deterministic secp256k1
 * private key (via ethers.js) and emits a Cairo-ready (pubkey,
 * signature) tuple the verifier accepts directly.
 *
 * Envelope shape matches src/signer/secp256k1/verifier.cairo:
 *   pubkey    = [x_lo, x_hi, y_lo, y_hi]
 *   signature = [r_lo, r_hi, s_lo, s_hi, y_parity]
 */

import { SigningKey, getBytes } from 'ethers';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Deterministic private key = 0x0102..0x20.
const PRIV_HEX = '0x0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20';
const signingKey = new SigningKey(PRIV_HEX);

// Use the SNIP-12 vector from Phase 1 as the message hash the verifier is
// asked to check. The wallet side signs over this same felt252 directly.
const MESSAGE_HASH = 0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2fn;

// Normalize the felt to a 32-byte BE hex (ethers signs over bytes).
const hashHex = '0x' + MESSAGE_HASH.toString(16).padStart(64, '0');

// ethers `SigningKey.sign(hash)` produces a raw ECDSA signature over the
// 32-byte hash (no EIP-191 prefix). The wallet side must agree — for
// plain SECP256K1 kind we sign the raw hash; for EIP191 kind we apply
// the `personal_sign` prefix before signing (future follow-up).
const sig = signingKey.sign(hashHex);

// Extract uncompressed pubkey → (x, y).
const pubBytes = getBytes(signingKey.publicKey); // 0x04 || X(32) || Y(32)
if (pubBytes[0] !== 0x04 || pubBytes.length !== 65) {
  throw new Error('Unexpected pubkey encoding');
}
const xBytes = pubBytes.slice(1, 33);
const yBytes = pubBytes.slice(33, 65);

function bytesBeToU256(b) {
  // bytes[0] is MSB.
  let x = 0n;
  for (let i = 0; i < b.length; i++) x = (x << 8n) | BigInt(b[i]);
  const low = x & ((1n << 128n) - 1n);
  const high = x >> 128n;
  return { low, high };
}

const pub = {
  x: bytesBeToU256(xBytes),
  y: bytesBeToU256(yBytes),
};

const r = bytesBeToU256(getBytes(sig.r));
const s = bytesBeToU256(getBytes(sig.s));
// ethers `sig.v` is 27/28 or 0/1; normalize to 0/1 y_parity.
const yParity = sig.yParity; // boolean
const vFelt = yParity ? 1n : 0n;

const felt = (x) => '0x' + x.toString(16);

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-secp256k1-fixture.mjs.
//! Do not edit by hand.
//!
//! Private key: ${PRIV_HEX}
//! Signed hash: ${felt(MESSAGE_HASH)}
//! Pubkey X   : ${Buffer.from(xBytes).toString('hex')}
//! Pubkey Y   : ${Buffer.from(yBytes).toString('hex')}
//! r          : ${sig.r}
//! s          : ${sig.s}
//! y_parity   : ${yParity}

pub fn secp256k1_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn secp256k1_pubkey() -> Array<felt252> {
    array![
        ${felt(pub.x.low)},
        ${felt(pub.x.high)},
        ${felt(pub.y.low)},
        ${felt(pub.y.high)},
    ]
}

pub fn secp256k1_signature() -> Array<felt252> {
    array![
        ${felt(r.low)},
        ${felt(r.high)},
        ${felt(s.low)},
        ${felt(s.high)},
        ${felt(vFelt)},
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/signer_secp256k1_fixture.cairo');
writeFileSync(out, cairo);

console.log('Wrote', out);
console.log('message_hash =', felt(MESSAGE_HASH));
console.log('pubkey.x     =', felt(pub.x.low), felt(pub.x.high));
console.log('pubkey.y     =', felt(pub.y.low), felt(pub.y.high));
console.log('r            =', felt(r.low), felt(r.high));
console.log('s            =', felt(s.low), felt(s.high));
console.log('y_parity     =', yParity);
