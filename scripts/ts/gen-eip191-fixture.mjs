#!/usr/bin/env node
/**
 * EIP-191 secp256k1 fixture generator for V8 EIP191Secp256k1Verifier.
 *
 * Mirrors what MetaMask's `personal_sign` produces: the wallet
 * computes `keccak256("\x19Ethereum Signed Message:\n32" || msg_be32)`
 * internally and signs that. Here we use ethers's `Wallet.signMessage`
 * which follows the exact same recipe.
 *
 * Same SNIP-12 message hash as gen-secp256k1-fixture.mjs so reviewers
 * can diff: only the signature changes (because EIP-191 prepends
 * the prefix), pubkey is identical.
 */

import { Wallet, getBytes, hexlify } from 'ethers';
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const PRIV_HEX = '0x0102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f20';
const wallet = new Wallet(PRIV_HEX);

const MESSAGE_HASH = 0x5bcd634ce46c7234bd7a4b0959c3c5edeed7f569dcfb7b33e23d7e2197a2a2fn;

// 32 BE bytes of the SNIP-12 hash. ethers `signMessage(bytes)` will
// prepend `\x19Ethereum Signed Message:\n32` and keccak256, then sign.
const msgBe32 = getBytes('0x' + MESSAGE_HASH.toString(16).padStart(64, '0'));

// `signMessage(Uint8Array)` is the exact `personal_sign` recipe.
const sigHex = await wallet.signMessage(msgBe32);
// 65-byte hex string: r(32) || s(32) || v(1)
const sigBytes = getBytes(sigHex);
if (sigBytes.length !== 65) throw new Error('expected 65-byte sig');
const rBytes = sigBytes.slice(0, 32);
const sBytes = sigBytes.slice(32, 64);
const vByte = sigBytes[64];
// ethers v in {27, 28} → y_parity in {0, 1}.
const yParity = vByte === 28 ? 1n : 0n;

// Pubkey from the wallet's signing key.
const pubBytes = getBytes(wallet.signingKey.publicKey);
if (pubBytes[0] !== 0x04 || pubBytes.length !== 65) throw new Error('bad pubkey');
const xBytes = pubBytes.slice(1, 33);
const yBytes = pubBytes.slice(33, 65);

function bytesBeToU256(b) {
  let x = 0n;
  for (let i = 0; i < b.length; i++) x = (x << 8n) | BigInt(b[i]);
  return { low: x & ((1n << 128n) - 1n), high: x >> 128n };
}

const pub = { x: bytesBeToU256(xBytes), y: bytesBeToU256(yBytes) };
const r = bytesBeToU256(rBytes);
const s = bytesBeToU256(sBytes);
const felt = (x) => '0x' + x.toString(16);

const cairo = `//! AUTO-GENERATED by scripts/ts/gen-eip191-fixture.mjs.
//! Do not edit by hand. Re-run if the EIP-191 verifier or fixture
//! inputs change.
//!
//! Recipe matches ethers \`Wallet.signMessage(bytes)\` and MetaMask
//! \`personal_sign\` — identical bytes-on-the-wire, identical hash.
//!
//! Private key: ${PRIV_HEX}
//! Signed hash: ${felt(MESSAGE_HASH)}
//!  (wallet side computes keccak256("\\x19Ethereum Signed Message:\\n32"
//!   || hash_be_32) and signs that)
//! Pubkey X   : ${hexlify(xBytes).slice(2)}
//! Pubkey Y   : ${hexlify(yBytes).slice(2)}
//! r          : ${hexlify(rBytes).slice(2)}
//! s          : ${hexlify(sBytes).slice(2)}
//! v          : ${vByte}  (y_parity = ${yParity})

pub fn eip191_message_hash() -> felt252 {
    ${felt(MESSAGE_HASH)}
}

pub fn eip191_pubkey() -> Array<felt252> {
    array![
        ${felt(pub.x.low)},
        ${felt(pub.x.high)},
        ${felt(pub.y.low)},
        ${felt(pub.y.high)},
    ]
}

pub fn eip191_signature() -> Array<felt252> {
    array![
        ${felt(r.low)},
        ${felt(r.high)},
        ${felt(s.low)},
        ${felt(s.high)},
        ${felt(yParity)},
    ]
}
`;

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../tests/signer_eip191_fixture.cairo');
writeFileSync(out, cairo);

console.log('Wrote', out);
console.log('message_hash =', felt(MESSAGE_HASH));
console.log('pubkey.x     =', felt(pub.x.low), felt(pub.x.high));
console.log('pubkey.y     =', felt(pub.y.low), felt(pub.y.high));
console.log('r            =', felt(r.low), felt(r.high));
console.log('s            =', felt(s.low), felt(s.high));
console.log('y_parity     =', yParity);
